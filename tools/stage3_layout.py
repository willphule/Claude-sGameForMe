#!/usr/bin/env python3
"""Builds src/stage3map.js, the Great Bell stage. Legend is in src/level.js.

Run from the repository root:  python3 tools/stage3_layout.py
"""
W, H = 140, 66
g = [['#'] * W for _ in range(H)]


def fill(x0, y0, x1, y1, ch):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            g[y][x] = ch


def put(x, y, ch):
    g[y][x] = ch


# ---------- A. The Sea Gate (the undercroft under the belfry) ----------
fill(1, 52, 79, 61, ' ')
put(3, 61, '@')
put(6, 61, 'N')                      # the Treasury ledger
# 1. push the block to the wall to climb it
put(14, 61, 'X')
fill(22, 58, 27, 61, '#')
put(29, 61, 'C')
# 2. push the block under the ledge; the gears only turn in THEN
put(32, 61, 'X')
fill(38, 58, 45, 61, '#')
fill(38, 57, 45, 57, 'G')
# 3. drop the block off the shelf onto the plate, which holds the door open
put(47, 61, 'C')
fill(49, 59, 50, 59, 'P')
fill(53, 57, 59, 57, '#')
put(55, 56, 'X')
put(60, 62, '_')
put(64, 61, 'N')                     # Teodor's notes
fill(68, 52, 68, 57, '#')
fill(68, 58, 68, 61, '=')
put(72, 61, 'C')

# ---------- B. The counterweight shaft (the Great Bell tolls up here) ----------
fill(81, 15, 99, 61, ' ')
fill(80, 58, 80, 61, ' ')            # the way in from the undercroft
fill(81, 50, 99, 61, '~')            # flooded in NOW
fill(81, 49, 84, 49, '#')            # first ledge
fill(81, 44, 99, 45, 'F')            # rubble plug: solid in NOW, gone in THEN
fill(87, 46, 88, 46, 'P')
fill(91, 43, 92, 43, 'P')
fill(95, 40, 99, 40, '#')            # second ledge
put(91, 33, 'O')
fill(81, 35, 85, 35, '#')            # third ledge
put(82, 34, 'N')                     # the clockmaker's notebook
put(87, 27, 'B')
put(92, 22, 'B')
fill(95, 21, 99, 21, '#')            # top ledge, up into the corridor

# ---------- corridor to the bell chamber ----------
fill(100, 16, 105, 18, ' ')
put(101, 18, 'C')
put(103, 18, 'N')                    # Ilse's last note
fill(105, 16, 105, 18, '|')

# ---------- C. The Great Bell chamber ----------
fill(106, 4, 135, 18, ' ')
fill(106, 15, 135, 18, '~')          # flooded in NOW
fill(116, 7, 125, 7, '#')            # the headstock beam the bell hangs from
put(120, 8, 'Q')
fill(106, 13, 111, 13, '#')          # left gallery
fill(130, 13, 135, 13, '#')          # right gallery
fill(112, 16, 113, 16, 'P')
fill(128, 16, 129, 16, 'P')
fill(113, 10, 114, 10, 'P')          # brass steps up to the beam (THEN only)
fill(127, 10, 128, 10, 'P')
put(107, 12, 'L')
put(134, 12, 'L')
put(120, 6, 'L')
put(113, 4, 'O')
put(128, 4, 'O')

rows = [''.join(r) for r in g]
with open('src/stage3map.js', 'w') as f:
    f.write('// Stage 3: the Great Bell. Legend is in level.js. Generated by tools/stage3_layout.py.\n')
    f.write('export const MAP3 = [\n')
    for r in rows:
        f.write(f"  '{r}',\n")
    f.write('];\n')
print('wrote src/stage3map.js', W, 'x', H)
